import jsPDF from 'jspdf';
import 'jspdf-autotable';
import * as XLSX from 'xlsx';

export function exportTableToExcel(dataList, fileName = 'Keyword_Intelligence_Report') {
  const worksheet = XLSX.utils.json_to_sheet(dataList || []);
  const workbook = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(workbook, worksheet, 'Keywords');
  XLSX.writeFile(workbook, `${fileName}.xlsx`);
}

export function exportAuditToPDF(domain, auditData) {
  const doc = new jsPDF('p', 'pt', 'a4');

  doc.setFillColor(15, 23, 42);
  doc.rect(0, 0, 595, 80, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFontSize(22);
  doc.text('EXECUTIVE DIGITAL INTELLIGENCE REPORT', 40, 42);

  doc.setFontSize(10);
  doc.setTextColor(148, 163, 184);
  doc.text(`Domain: ${domain}  |  Generated by Flywheel AI Enterprise Platform`, 40, 62);

  doc.autoTable({
    startY: 100,
    head: [['Metric Category', 'Score / Value', 'Benchmark Benchmark']],
    body: [
      ['Global Traffic Rank', `#${(auditData?.overview?.global_rank || 'N/A')}`, 'Top 0.5% Global'],
      ['Estimated Monthly Visits', `${(auditData?.overview?.total_monthly_visits || 'N/A')}`, 'Active Growth Trajectory'],
      ['Overall SEO Health', `${(auditData?.seo_intelligence?.overall_score || 70)}/100`, 'Good (Optimization Available)']
    ],
    theme: 'striped',
    headStyles: { fillColor: [79, 70, 229] }
  });

  if (auditData?.keyword_research_table && auditData.keyword_research_table.length > 0) {
    const tableRows = auditData.keyword_research_table.slice(0, 25).map(k => [k.keyword, k.search_volume?.toLocaleString?.() || k.search_volume, `${k.difficulty}/100`, `$${k.cpc_usd}`, k.intent]);
    doc.autoTable({
      startY: doc.lastAutoTable ? doc.lastAutoTable.finalY + 30 : 200,
      head: [['Target Keyword', 'Monthly Volume', 'Difficulty', 'Est. CPC', 'Search Intent']],
      body: tableRows,
      theme: 'grid',
      headStyles: { fillColor: [15, 23, 42] }
    });
  }

  doc.save(`${domain}_Digital_Intelligence_Audit.pdf`);
}
